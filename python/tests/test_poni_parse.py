def test_parse_invalid_detector_config_is_tolerated(tmp_path):
    """A malformed Detector_config JSON must not crash the parser."""
    path = _write_poni(tmp_path, [
        "Distance: 0.1",
        "Wavelength: 1.5e-10",
        "Detector: Detector",
        "Detector_config: {not valid json",
    ])
    data = parse_poni_file(path)
    assert data is not None
    assert "pixel_size" not in data or data["pixel_size"] > 0
